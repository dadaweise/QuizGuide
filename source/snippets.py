S["n1_fix"] = r"""async fn view_warehouse_list(&self) -> Result<Vec<WarehouseResponse>, StatusCode> {

    let warehouses = self.repository.load_warehouses().await;
    if warehouses.is_err() {
        return Err(StatusCode::INTERNAL_SERVER_ERROR);
    }

    // Satu query untuk SEMUA inventory, bukan satu query per warehouse
    let inventory = self.repository.load_all_warehouse_inventory().await;
    if inventory.is_err() {
        return Err(StatusCode::INTERNAL_SERVER_ERROR);
    }

    // Kelompokkan item berdasarkan warehouse_id
    let mut items_by_warehouse: HashMap<i32, Vec<WarehouseInventoryItem>> = HashMap::new();
    for item in inventory.unwrap() {
        let medicine_name = match item.medicine.into_option() {
            Some(medicine) => medicine.name,
            None => "Unnamed Medicine".to_string(),
        };

        items_by_warehouse.entry(item.warehouse_id).or_default().push(WarehouseInventoryItem {
            medicine_id: item.medicine_id,
            medicine_name,
            quantity: item.quantity,
            reorder_threshold: Some(item.reorder_threshold),
        });
    }

    let warehouses = warehouses.unwrap();
    let mut warehouse_data = Vec::new();

    for warehouse in warehouses {
        let items = items_by_warehouse.remove(&warehouse.id).unwrap_or_default();

        let region = match warehouse.region.into_option() {
            Some(region) => region.name,
            None => String::new(),
        };

        warehouse_data.push(WarehouseResponse {
            id: warehouse.id,
            name: warehouse.name,
            region,
            capacity: warehouse.capacity,
            x_position: warehouse.x_position,
            y_position: warehouse.y_position,
            inventory: items,
        });
    }

    Ok(warehouse_data)
}"""

